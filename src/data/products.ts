/**
 * Process families. A product's `processCode` names the downstream archetype
 * its train belongs to, so two molecules sharing a code share equipment — the
 * question a facility actually has to answer before it buys anything.
 */
export const PROCESS_FAMILIES: { code: string; label: string; productIds: string[] }[] = (() => {
  const by = new Map<string, string[]>();
  for (const p of PRODUCTS) {
    const arr = by.get(p.processCode);
    if (arr) arr.push(p.id);
    else by.set(p.processCode, [p.id]);
  }
  return [...by.entries()]
    .sort((a, b) => Number(a[0].slice(1)) - Number(b[0].slice(1)))
    .map(([code, productIds]) => ({
      code,
      label: `${code} · ${productIds.length} molecule${productIds.length === 1 ? '' : 's'}`,
      productIds,
    }));
})();

/** Products whose default host is a given strain — the Organisms cross-link. */
export function productsForStrain(strainId: string): Product[] {
  return PRODUCTS.filter((p) => p.defaultStrainId === strainId);
}
