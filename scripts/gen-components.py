"""`pnpm gen:components`: write COMPONENTS.md from the package map (execution prompt §7.2,
§10 stage 8.3). The map is the one `core/tests/test_boundaries.py` enforces: what each package
may import, what it must never import, and each documented exception with its reason. What a
package and a module own is the first paragraph of its own docstring; the client's folders are
listed from `src/`. `--check` writes nothing and fails when the file differs from the map."""
from __future__ import annotations

import ast
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE = ROOT / "core" / "openferment_core"
DOC = ROOT / "COMPONENTS.md"

# §7.2's rows beyond the packages test_boundaries.py holds to an import list, each with what the
# execution prompt says it owns and its rule, in the prompt's order.
ROWS_BEYOND = [
    ("tools/", "the one registry; reads and writes for every caller", "the domain packages' service functions",
     "file writes"),
    ("workers/ + flowsheets/ + vendor/pisces_sff", "engine code in its own process",
     "biosteam, thermosteam, biorefineries", "the service"),
    ("api.py", "routers; thin", "the packages above", "business logic"),
    ("src/", "rendering server records and events", "/api, /rag", "any scientific computation or provenance decision"),
]


def boundaries():
    spec = importlib.util.spec_from_file_location("test_boundaries", ROOT / "core" / "tests" / "test_boundaries.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def first_paragraph(path: Path) -> str:
    doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8"))) or ""
    return " ".join(doc.split("\n\n")[0].split())


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def names(items: set[str]) -> str:
    return ", ".join(f"`{n.removeprefix('openferment_core.')}`" for n in sorted(items)) or "—"


def render() -> str:
    b = boundaries()
    out = [
        "# Components",
        "",
        "Generated by `pnpm gen:components` from the package map `core/tests/test_boundaries.py` enforces",
        "(execution prompt §7.2) and each package's and module's own docstring. Never edited by hand:",
        "`pnpm verify` runs `gen:components --check`.",
        "",
        "## The package map",
        "",
        "| Package | May import (openFerment's own) | Must never import |",
        "|---|---|---|",
    ]
    for package, allowed in b.MAY.items():
        out.append(f"| `{package}/` | {names(allowed)} | {names(b.NEVER.get(package, set()))} |")
    out += ["", "The rows the boundary test holds by other means (the worker's side by `test_workers.py`, the",
            "tool registry by `check:tools`):", "", "| Part | Owns | May import | Must not |", "|---|---|---|---|"]
    out += [f"| `{a}` | {cell(o)} | {cell(m)} | {cell(n)} |" for a, o, m, n in ROWS_BEYOND]
    out += ["", "Documented exceptions, each with its reason:", "", "| Package | Imports | Because |", "|---|---|---|"]
    out += [f"| `{p}/` | `{m}` | {cell(why)} |" for (p, m), why in b.EXCEPTIONS.items()]

    out += ["", "## Packages", ""]
    for d in sorted(p for p in CORE.iterdir() if p.is_dir() and (p / "__init__.py").exists()):
        out += [f"### `{d.name}/`", "", first_paragraph(d / "__init__.py"), "", "| Module | What it says it is |",
                "|---|---|"]
        out += [f"| `{m.name}` | {cell(first_paragraph(m))} |" for m in sorted(d.glob("*.py")) if m.name != "__init__.py"]
        out.append("")

    out += ["## Modules at the top of `openferment_core`", "", "| Module | What it says it is |", "|---|---|"]
    out += [f"| `{m.name}` | {cell(first_paragraph(m))} |" for m in sorted(CORE.glob("*.py")) if m.name != "__init__.py"]

    out += ["", "## The client (`src/`)", "", "| Folder | Files |", "|---|---|"]
    src = ROOT / "src"
    for d in sorted(p for p in src.iterdir() if p.is_dir()):
        files = sorted(f.name for f in d.rglob("*") if f.suffix in (".ts", ".tsx") and ".test." not in f.name)
        out.append(f"| `src/{d.name}/` | {len(files)}: {', '.join(f'`{f}`' for f in files[:60])}"
                   f"{' …' if len(files) > 60 else ''} |")
    out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not DOC.exists() or DOC.read_text(encoding="utf-8") != text:
            print("✗ COMPONENTS.md differs from the package map. Run `pnpm gen:components`.")
            return 1
        print("✓ COMPONENTS.md is what the package map writes.")
        return 0
    DOC.write_text(text, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
