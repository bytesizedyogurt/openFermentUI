/**
 * The unit engine's answers, recorded (OF-BLD-012 §5.3).
 *
 * `src/engine/units.ts` is the reference implementation and
 * `core/openferment_core/units.py` is its mirror, working from the same table.
 * Two implementations of one algorithm drift the first time somebody fixes a
 * bug in one of them, so the TypeScript side's answers to a fixed set of
 * inputs are written down here and the Python test asserts equality on every
 * one. Nothing in this file is a hand-typed expected value: each case is what
 * `units.ts` actually returned at export time. If the two sides disagree, this
 * side is right — that is the whole arrangement.
 *
 * THE CASES ARE CHOSEN TO BE AWKWARD. Aliases that differ only by case ('mM' is
 * millimolar, 'mm' is millimetres), affine temperature, the superscript-blind
 * fallback, middot separators, an unknown unit, an empty unit, and the refusals
 * that carry a reason. Twenty easy cases would prove less than these.
 *
 * Emits core/tests/fixtures/units.json. Regenerated by `pnpm test:core` so the
 * fixture never lags the engine, and gitignored for the same reason
 * corpus.json is: a committed copy would be a second source that drifts.
 *
 * It also emits core/tests/fixtures/resolvers.json (OF-BLD-014 §2.1): what
 * `normalizeStrain` and `carbonSourceId` answer for a fixed set of wordings.
 * `validate.py` mirrors the whole-word rule both use, and
 * tests/test_validate.py asserts it answers the same, case by case. Same
 * arrangement, same reason, same exporter.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import {
  convert,
  explainRefusal,
  normalizeUnit,
  quantityEquals,
  toSI,
  unitFamily,
} from '../src/engine/units';
import { normalizeStrain } from '../src/data/strains';
import { carbonSourceId } from '../src/data/vocabulary';

const OUT = 'core/tests/fixtures/units.json';
const OUT_RESOLVERS = 'core/tests/fixtures/resolvers.json';

// ── normalise: raw notation → table key, and its family ────────────────
const NORMALIZE_INPUTS = [
  'g/L', // the commonest alias
  'mg L-1', // ASCII superscript, matched by the fallback
  'mg·L⁻¹', // middot separator (the §5.3 example)
  'mg⋅L⁻¹', // dot operator, the other middot
  'µg/mL',
  'ug/ml', // ASCII micro, lower-case alias
  '1/h',
  'per day',
  'degC',
  'K', // in the table directly
  'k', // lower-case alias to the same
  '% dw',
  '%TSP', // no space — needed an alias
  'mM', // millimolar via lower-case alias …
  'mm', // … but 'mm' is in the table as millimetres
  'M', // molar via the alias …
  'm', // … and 'm' is the metre
  'G L-1', // wrong case, superscript-blind fallback
  'kg/m3',
  'g/L/h',
  'µmol/m²/s',
  '', // pH — the empty unit is a real key
  'furlongs', // unknown
  '  g/L  ', // whitespace
  // OF-BLD-014 §2.1 — the polymer units and every alias the step names.
  '% CDW', // the key itself
  '%CDW', // no space, through the lower-cased alias
  '% cdw',
  'wt%',
  '% (w/w)',
  'kDa',
  'kda',
  'KDa', // wrong case, reaches the lower-cased alias
  'kg/mol',
  'Da',
  'g mol⁻¹',
  'g mol-1', // ASCII superscript, by the fallback
  // The minus sign journals print (live test, 2026-10-16): U+2212 and the en dash.
  'g L\u22121',
  'g g\u22121',
  'h\u22121',
  'g L\u22121 h\u22121',
  'g L\u20131',
];

const normalize = NORMALIZE_INPUTS.map((raw) => ({
  raw,
  unit: normalizeUnit(raw),
  family: unitFamily(raw),
}));

// ── convert: value, from, to → result (or the error class) ─────────────
const CONVERT_INPUTS: [number, string, string][] = [
  [2.5, 'mg/L', 'g L⁻¹'],
  [37, '°C', 'K'],
  [98.6, '°F', '°C'],
  [300, 'K', '°C'],
  [1, 'd⁻¹', 'h⁻¹'],
  [24, 'g L⁻¹ d⁻¹', 'g L⁻¹ h⁻¹'],
  [5, 'g/g/h', 'mg g⁻¹ h⁻¹'],
  [100, 'mg/dL', 'g L⁻¹'],
  [1, 'kg m⁻³', 'g L⁻¹'],
  [3.6, 'MJ kg⁻¹', 'kWh kg⁻¹'],
  [1, 'g/L', 'h⁻¹'], // incompatible — must throw
  [1, 'g/L', 'furlongs'], // unknown — must throw
  // OF-BLD-014 §2.1
  [62, 'wt%', '% CDW'],
  [450, 'kDa', 'g mol⁻¹'],
  [1.5, 'kg/mol', 'Da'],
  [250000, 'Da', 'kDa'],
  [40, '% CDW', 'g/L'], // a share of dry cells is not a titre — must throw
  [40, '% CDW', '%'], // nor a bare percentage — must throw
];

const conversions = CONVERT_INPUTS.map(([value, from, to]) => {
  try {
    return { value, from, to, result: convert(value, from, to), error: null };
  } catch (e) {
    return { value, from, to, result: null, error: (e as Error).message };
  }
});

// ── toSI: the family's designated display twin ─────────────────────────
const SI_INPUTS: [number, string][] = [
  [1, 'g L⁻¹'],
  [300, 'K'],
  [2, 'mg/g'],
  [5, 'unknownunit'], // passes through untouched
  [62, 'wt%'], // OF-BLD-014 §2.1
  [450000, 'g mol⁻¹'],
];
const si = SI_INPUTS.map(([value, unit]) => ({ value, unit, si: toSI(value, unit) }));

// ── refusals: the conversions that come with a reason ──────────────────
const REFUSAL_INPUTS: [string, string][] = [
  ['% TSP', 'g/L'],
  ['g/L', '% TSP'], // symmetric
  ['EUR kg⁻¹', 'USD kg⁻¹'],
  ['% TSP', '% DW'],
  ['g/L', 'h⁻¹'], // incompatible but no recorded trap → null
  ['g/L', 'mg/L'], // same family → null
  ['furlongs', 'g/L'], // unknown → null
  // OF-BLD-014 §2.1 — the conversion needs that culture's biomass density.
  ['% CDW', 'g/L'],
  ['mg/L', 'wt%'], // symmetric, through the aliases
  ['% CDW', '% DW'], // another family, no recorded trap → null
  ['kDa', 'g/L'], // incompatible but no recorded trap → null
];
const refusals = REFUSAL_INPUTS.map(([from, to]) => ({ from, to, because: explainRefusal(from, to) }));

// ── quantityEquals: the tolerance rule §6.2 reuses ─────────────────────
const EQUALS_INPUTS: [{ value: number; unit: string }, { value: number; unit: string }, number][] = [
  [{ value: 4.2, unit: 'g/L' }, { value: 4200, unit: 'mg/L' }, 2],
  [{ value: 4.2, unit: 'g/L' }, { value: 4.28, unit: 'g/L' }, 2], // 1.9 % — inside
  [{ value: 4.2, unit: 'g/L' }, { value: 4.3, unit: 'g/L' }, 2], // 2.3 % — outside
  [{ value: 4.2, unit: 'g/L' }, { value: 42, unit: 'g/L' }, 2],
  [{ value: 1, unit: '% TSP' }, { value: 1, unit: 'g/L' }, 2], // families differ
  [{ value: 0, unit: 'g/L' }, { value: 0, unit: 'mg/L' }, 2], // zero against zero
  [{ value: 4.2, unit: 'g/L' }, { value: 4.22, unit: 'g/L' }, 0.5], // §2.4's tighter tolerance
];
const equals = EQUALS_INPUTS.map(([a, b, tolerancePct]) => ({
  a,
  b,
  tolerancePct,
  result: quantityEquals(a, b, tolerancePct),
}));

const fixture = {
  generatedBy: 'scripts/export-unit-fixtures.ts — do not edit; regenerate with pnpm export:unit-fixtures',
  normalize,
  conversions,
  si,
  refusals,
  equals,
};

mkdirSync('core/tests/fixtures', { recursive: true });
writeFileSync(OUT, JSON.stringify(fixture, null, 2) + '\n');

// ── resolvers: a paper's wording → strain id or carbon source (§2.1) ───
// The exact alias, the whole-word rule, and the cases it must refuse: a
// species alone, an alias glued to other letters, two different ids in one
// wording, a key that is only a property of every JavaScript object.
const STRAIN_INPUTS = [
  'cw15', // exact
  '  CW15  ', // exact, after trimming and lower-casing
  'Chlamydomonas reinhardtii UVM4', // a designation inside the wording
  'C. reinhardtii cc124 grown mixotrophically',
  'Chlamydomonas  reinhardtii   cw15-302', // runs of whitespace collapse
  'Escherichia coli BL21(DE3)', // bl21 as a whole word
  'E. coli', // exact, punctuation inside the alias
  'Pichia pastoris GS115',
  'Chlamydomonas reinhardtii', // the species alone: no alias
  'Cupriavidus necator', // no alias at all
  'uvm40', // glued to a digit: not uvm4
  'xuvm4', // glued to a letter: not uvm4
  'cw15 and UVM4 crossed', // two ids → null
  'E. coli expressing bovine beta-casein', // two ids → null
  'CC-137c', // two aliases (cc-137c, 137c), one id
  '',
  'constructor', // not an alias, whatever Object.prototype holds
];
const CARBON_INPUTS = [
  'glucose',
  'Glucose', // case
  'D-glucose', // its own spelling, and glucose inside it
  'crude glycerol', // a spelling inside the wording
  'sodium acetate',
  'wheat straw hydrolysate',
  'a mixture of sugars',
  'glucose and xylose', // two ids → null
  'glucosamine', // glued: not glucose
  'waste frying oil', // not in the list
  '',
  'toString',
];
const resolvers = {
  generatedBy: 'scripts/export-unit-fixtures.ts — do not edit; regenerate with pnpm export:unit-fixtures',
  strains: STRAIN_INPUTS.map((text) => ({ text, id: normalizeStrain(text) })),
  carbon: CARBON_INPUTS.map((text) => ({ text, id: carbonSourceId(text) })),
};
writeFileSync(OUT_RESOLVERS, JSON.stringify(resolvers, null, 2) + '\n');

const pairs = normalize.length + conversions.length + si.length + refusals.length + equals.length;
console.log('\nopenFerment unit fixtures');
console.log('─────────────────────────');
console.log(`  normalize    ${normalize.length} (${normalize.filter((n) => n.unit === null).length} unknown)`);
console.log(`  conversions  ${conversions.length} (${conversions.filter((c) => c.error).length} refused)`);
console.log(`  toSI         ${si.length}`);
console.log(`  refusals     ${refusals.length} (${refusals.filter((r) => r.because).length} carry a reason)`);
console.log(`  equals       ${equals.length}`);
console.log(`  pairs        ${pairs} recorded from the TypeScript engine`);
console.log(`  resolvers    ${resolvers.strains.length} strain wordings, ${resolvers.carbon.length} carbon wordings`);
console.log(`\n✓ ${OUT}`);
console.log(`✓ ${OUT_RESOLVERS}`);
