/**
 * The unit engine's answers, recorded (OF-BLD-012 §5.3).
 *
 * `src/engine/units.ts` is the reference implementation and
 * `core/openferment_core/units.py` is its mirror, working from the same table.
 * Two implementations of one algorithm drift the first time somebody fixes a
 * bug in one of them, so the TypeScript side's answers to a fixed set of
 * inputs are written down here and the Python test asserts equality on every
 * one. Nothing in this file is a hand-typed expected value: each case is what
 * `units.ts` actually returned at export time. If the two sides disagree, this
 * side is right — that is the whole arrangement.
 *
 * THE CASES ARE CHOSEN TO BE AWKWARD. Aliases that differ only by case ('mM' is
 * millimolar, 'mm' is millimetres), affine temperature, the superscript-blind
 * fallback, middot separators, an unknown unit, an empty unit, and the refusals
 * that carry a reason. Twenty easy cases would prove less than these.
 *
 * Emits core/tests/fixtures/units.json. Regenerated by `pnpm test:core` so the
 * fixture never lags the engine, and gitignored: a committed copy would be a
 * second source that drifts.
 *
 * It also emits core/tests/fixtures/resolvers.json (OF-BLD-014 §2.1): what
 * `normalizeStrain` and `carbonSourceId` answer for a fixed set of wordings.
 * `validate.py` mirrors the whole-word rule both use, and
 * tests/test_validate.py asserts it answers the same, case by case. Same
 * arrangement, same reason, same exporter.
 *
 * And core/tests/fixtures/fields.json (alpha 2.0): the record fields as
 * src/data/ontology.ts holds them and the vocabulary as src/data/vocabulary.ts
 * holds it, which tests/test_schema.py holds equal to
 * core/openferment_core/schema/fields.yaml and vocabulary.yaml.
 */
