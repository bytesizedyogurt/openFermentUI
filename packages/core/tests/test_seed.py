def test_every_model_field_becomes_a_column_or_is_declared_external() -> None:
    """The guarantee the whole generator exists for.

    A field added to a model cannot be forgotten in the DDL, because the DDL
    does not have a list of fields to forget it from.
    """
    for table in seed.tables():
        assert table.model is not None
        covered = {c.field for c in table.columns if c.field is not None}
        for name in table.model.model_fields:
            assert name in covered or name in table.externalised, (
                f"{table.model.__name__}.{name} has no column in {table.name} and is not "
                f"declared as externalised. Regenerate, or declare it."
            )


def test_every_column_is_derived_or_carries_its_reason() -> None:
    """A hand-written column with no stated reason cannot survive review."""
    for table in seed.tables():
        for column in table.columns:
            if column.derived:
                continue
            assert column.why, f"{table.name}.{column.name} is synthetic and says nothing"
            assert column.name in {c.name for c in SYNTHETIC.get(table.name, ())}


def test_the_only_externalised_field_is_the_audit_trail() -> None:
    external = {(t.name, field) for t in seed.tables() for field in t.externalised}
    assert external == {(AUDIT.parent, AUDIT.field)}


