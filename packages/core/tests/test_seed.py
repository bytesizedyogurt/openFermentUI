def _dumped(model: type[BaseModel], raw: dict[str, Any]) -> dict[str, Any]:
    """A corpus entry as the model re-emits it — the only fair comparison.

    The corpus writes `"value": 15` where the model's `float | str` makes it
    15.0, so comparing a row round trip against the raw JSON would report a
    difference that is not one. Both sides go through the model; what is being
    tested is what the database did in between.
    """
    return model.model_validate(raw).model_dump(mode="json", by_alias=True, exclude_none=True)


