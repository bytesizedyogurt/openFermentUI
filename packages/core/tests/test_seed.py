def test_reference_tables_converge_on_a_reload(db: sqlite3.Connection, corpus_dir: Path) -> None:
    """Papers, ontology, strains, protocols, scenarios and learn modules are a
    projection of the JSON, so re-running the loader must not duplicate them."""
    corpus = seed.read_corpus(corpus_dir)
    cursor = db.cursor()
    seed.load(cursor, corpus, seed.SQLITE)
    before = db.execute('SELECT count(*) FROM "papers"').fetchone()[0]
    seed.load(cursor, corpus, seed.SQLITE, append=True)
    assert db.execute('SELECT count(*) FROM "papers"').fetchone()[0] == before


