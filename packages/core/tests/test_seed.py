def test_reserved_words_are_quoted() -> None:
    """`from` and `to` are columns. Unquoted, the audit table would not parse.

    `test_seed_ddl.py` would already have failed to parse the audit table, so
    this one is about saying out loud which identifiers that depends on.
    """
    sql = seed.schema_sql(seed.POSTGRES)
    assert '"from" JSONB' in sql
    assert '"to" JSONB' in sql
    for table in seed.tables():
        for column in table.columns:
            assert f'"{column.name}"' in sql


def test_append_only_tables_carry_both_triggers_and_the_revoke() -> None:
    sql = seed.schema_sql(seed.POSTGRES)
    append_only = [t.name for t in seed.tables() if t.append_only]
    assert set(append_only) == {"records", "audit_event"}
    for name in append_only:
        assert f'BEFORE UPDATE OR DELETE ON "{name}"' in sql
        # TRUNCATE fires no row-level trigger; without this it is a way out.
        assert f'BEFORE TRUNCATE ON "{name}"' in sql
        assert f'REVOKE UPDATE, DELETE, TRUNCATE ON TABLE "{name}" FROM PUBLIC' in sql


def test_nothing_else_is_append_only_by_accident() -> None:
    """An upsert exists for every table that is not append-only, and for none
    that is — the two lists are the same list, read twice."""
    for table in seed.tables():
        if table.append_only:
            with pytest.raises(ValueError):
                seed.rows.upsert_sql(table, seed.POSTGRES)
        else:
            assert "ON CONFLICT" in seed.rows.upsert_sql(table, seed.POSTGRES)


