def test_audit_from_and_to_round_trip_whatever_they_hold(db: sqlite3.Connection) -> None:
    """`AuditEvent.from` is `Any` because a correction can be of any shape.

    The seeded corpus never populates it — every one of its 134 audit events is
    a curation note with no from/to — so this is the only place the two columns
    are exercised, and it exercises them with the three shapes the TypeScript's
    `unknown` allows.
    """
    record = _one_record(
        audit=[
            {"at": "t", "who": "w", "action": "number", "from": 1.5, "to": 2.5},
            {"at": "t", "who": "w", "action": "string", "from": "unverified", "to": "verified"},
            {
                "at": "t",
                "who": "w",
                "action": "object",
                "from": {"value": 1.0, "unit": "g/L"},
                "to": {"value": 1000.0, "unit": "mg/L"},
            },
        ]
    )
    _insert(db, record)
