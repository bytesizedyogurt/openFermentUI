"""Tests for the seed loader.

Read the section headings before the assertions: they are what says which
claims are PROVEN and which are only CHECKED, because there is no Postgres
server in this environment and pretending otherwise would be worse than useless.

    ── generated, not written ──   pure Python: the columns come from the models
    ── the Postgres schema ──      PARSED and linted. Never executed. sqlglot
                                   reads the emitted DDL back and the tables it
                                   finds are compared with the tables the models
                                   imply — so "this SQL declares what I meant"
                                   is checked, and "this SQL runs on Postgres 16"
                                   is not.
    ── the schema, executed ──     the SAME generated schema, rendered for
                                   SQLite, actually run. The real corpus is
                                   loaded and read back; an UPDATE on the
                                   records table is refused by the database; a
                                   correction is appended; the CHECK constraints
                                   reject values the models would reject. Every
                                   claim in this block is executed.

What the SQLite block cannot prove: the Postgres spelling of anything in
`dialect.py` (JSONB, IDENTITY, TIMESTAMPTZ, plpgsql), the `BEFORE TRUNCATE`
trigger (SQLite has no TRUNCATE), and the REVOKE (SQLite has no privileges).
"""

